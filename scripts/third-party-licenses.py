#!/usr/bin/env python3
"""Write THIRD-PARTY-LICENSES.md: every third-party crate compiled into the
perseverus-sdk library (normal dependencies with default features; build
scripts, proc macros and dev-dependencies don't end up in the library).

    python3 scripts/third-party-licenses.py      # from the repo root

Run it after changing dependencies, and commit the result.
"""
import json
import subprocess
import sys

meta = json.loads(subprocess.run(
    ["cargo", "metadata", "--format-version", "1", "--locked"],
    check=True, capture_output=True, text=True).stdout)
pkgs = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
ours = set(meta["workspace_members"])
root = next(i for i in ours if pkgs[i]["name"] == "perseverus-sdk")


def is_proc_macro(p):
    return any("proc-macro" in t["kind"] for t in p["targets"])


seen, stack = set(), [root]
while stack:
    i = stack.pop()
    if i in seen:
        continue
    seen.add(i)
    for d in nodes[i]["deps"]:
        if any(k["kind"] is None for k in d["dep_kinds"]) and not is_proc_macro(pkgs[d["pkg"]]):
            stack.append(d["pkg"])

rows = sorted((pkgs[i]["name"], pkgs[i]["version"], pkgs[i].get("license") or "see crate",
               pkgs[i].get("repository") or "") for i in seen if i not in ours)
by_license = {}
for _, _, lic, _ in rows:
    by_license[lic] = by_license.get(lic, 0) + 1

out = ["# Third-party licenses", "",
       "The SDK itself is MIT-licensed (see [LICENSE](LICENSE)). The library also contains "
       f"the {len(rows)} third-party crates below, each under its own license. All of them are "
       "permissive or offer a permissive choice; where a crate offers several licenses "
       "(\"MIT OR Apache-2.0\"), you may use it under either.", "",
       "Two that come with a condition worth knowing:", "",
       "- **UniFFI** (`uniffi*`, MPL-2.0): file-level copyleft. Using it, as the SDK does, "
       "puts no condition on your code or the SDK's; only changes to UniFFI's own source files "
       "would have to be published under MPL-2.0.",
       "- **webpki-roots** (CDLA-Permissive-2.0): Mozilla's list of trusted certificate "
       "authorities, used for `https://` endpoints. If you distribute it, include its license text "
       "(it's in the crate).", "",
       "Generated by `scripts/third-party-licenses.py` from `Cargo.lock`. Regenerate after "
       "changing dependencies.", "",
       "## By license", "", "| License | Crates |", "|---|---|"]
out += [f"| {lic} | {n} |" for lic, n in sorted(by_license.items(), key=lambda x: -x[1])]
out += ["", "## Crates", "", "| Crate | Version | License | Source |", "|---|---|---|---|"]
out += [f"| {n} | {v} | {lic} | {repo} |" for n, v, lic, repo in rows]
open("THIRD-PARTY-LICENSES.md", "w").write("\n".join(out) + "\n")
print(f"THIRD-PARTY-LICENSES.md: {len(rows)} crates", file=sys.stderr)
